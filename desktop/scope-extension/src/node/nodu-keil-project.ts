async function safeFile(path: string, root: string): Promise<void> {
    const actual = await fs.realpath(path);
    if (!within(root, actual)) fail('keilPath', '工程引用了目录外的文件，无法生成可移动的 Keil 工程。');
    if ((await fs.lstat(path)).isSymbolicLink()) fail('keilPath', 'Keil 工程生成不跟随符号链接。');
}
async function collect(dir: string, root: string, out: Map<string, Buffer>, prefix: string): Promise<void> {
    await safeFile(dir, root);
    for (const entry of await fs.readdir(dir, { withFileTypes: true })) {
        const full = join(dir, entry.name), rel = `${prefix}/${entry.name}`;
        if (entry.isSymbolicLink()) fail('keilPath', `工具包包含符号链接：${rel}`);
        if (entry.isDirectory()) await collect(full, root, out, rel);
        else if (entry.isFile()) out.set(rel, await fs.readFile(full));
    }
}
async function atomic(path: string, data: string | Buffer): Promise<void> {
    await fs.mkdir(dirname(path), { recursive: true });
    const temp = `${path}.${randomUUID()}.tmp`;
    try { await fs.writeFile(temp, data, { flag: 'wx' }); await fs.rename(temp, path); }
    finally { await fs.rm(temp, { force: true }); }
}

export async function generateKeil(project: ProjectStatus, compileFile: string, resources: string, buildReservation?: string): Promise<KeilResult> {
    if (!supportsKeil(project)) fail('keilUnsupported', '支持 Nodu 原生 STM32F103C8T6 / STM32F407ZGT6 工程。');
    if (!project.trusted) fail('untrusted', '请先信任当前工程，再生成 Keil 配置。');
    const root = await fs.realpath(project.path);
    const lockDir = join(root, '.nodu');
    await fs.mkdir(lockDir, { recursive: true }); await safeFile(lockDir, root);
    const reservation = await fs.readFile(join(lockDir, 'keil-check.lock'), 'utf8').catch(() => undefined);
    if (reservation !== undefined && reservation !== buildReservation) fail('keilBusy', '这个工程正在进行编译兼容验证，请等待当前编译结束。');
    const lock = join(lockDir, 'keil-update.lock');
    const handle = await fs.open(lock, 'wx').catch(() => fail('keilLocked', '另一个窗口正在维护 Keil 工程。若 Nodu 曾异常退出，请关闭所有窗口后删除 .nodu/keil-update.lock 再试。'));
    try { return await generateLocked(project, compileFile, resources); }
    finally { await handle.close(); await fs.rm(lock, { force: true }); }
}

async function generateLocked(project: ProjectStatus, compileFile: string, resources: string): Promise<KeilResult> {
    if (!supportsKeil(project)) fail('keilUnsupported', '支持 Nodu 原生 F103C8 / F407ZG 工程；外部 CMake 工程需先适配构建语义。');
    if (!project.trusted) fail('untrusted', '请先信任当前工程，再生成 Keil 配置。');
    const root = await fs.realpath(project.path), dest = join(root, 'MDK-ARM');
    if (await exists(dest)) await safeFile(dest, root);
    const statePath = join(dest, STATE), file = join(dest, PROJECT);
    let state: State | undefined;
    if (await exists(statePath)) {
        await safeFile(statePath, root); state = JSON.parse(await fs.readFile(statePath, 'utf8'));
        if (state?.schema !== 1 || !state.assets || typeof state.generated !== 'string') fail('keilConflict', 'Keil 自动维护记录无效，未覆盖现有工程。');
    } else if (await exists(dest) && (await fs.readdir(dest)).length) fail('keilConflict', 'MDK-ARM 已有其他工程，未覆盖。请先移动或重命名该目录。');
    const toolkit = project.toolkit.root;
    if (!toolkit) fail('toolkitBroken', 'STM32 工具包不可用。');
    const sdk = await fs.realpath(join(toolkit!, 'sdk', project.chip.sdk.dir));
    const localDrivers = join(root, 'Drivers'), device = deviceInfo(project);
    const sdkRoot = await exists(join(localDrivers, `${device.series}_HAL_Driver`)) ? root : sdk;
    await safeFile(compileFile, root);
    const entries: CompileEntry[] = JSON.parse(await fs.readFile(compileFile, 'utf8'));
    const layout = await readLinkerLayout(project, compileFile);
    const app: string[] = [], hal: string[] = [], defines = new Set<string>(), includes = new Set<string>();
    const mapPath = async (value: string, directory: string): Promise<string> => {
        const source = resolve(directory, value), full = await fs.realpath(source);
        if (within(join(sdkRoot, 'Drivers'), full)) {
            await safeFile(source, sdkRoot);
            return `Drivers/${relative(join(sdkRoot, 'Drivers'), full).replace(/\\/g, '/')}`;
        }
        await safeFile(source, root);
        return relative(dest, full).replace(/\\/g, '/');
    };
    const units = new Map<string, SourceOptions>(), diagnosticFlags = new Set<string>();
    for (const entry of entries) {
        const full = resolve(entry.directory, entry.file);
        if (basename(full).toLowerCase() === device.startup) {
            await safeFile(full, root);
            const actual = await fs.readFile(full, 'utf8');
            const original = await fs.readFile(join(sdk, 'Drivers/CMSIS/Device/ST', device.series, 'Source/Templates/gcc', device.startup), 'utf8');
            const code = (text: string) => text.replace(/\/\*[\s\S]*?\*\/|\/\/[^\n]*/g, '').replace(/\s/g, '');
            if (code(actual) !== code(original)) fail('keilStartup', `${relative(root, full)} 含自定义启动代码，必须先提供等价的 Arm 启动文件，不能直接替换成通用启动文件。`);
            continue;
        }
        if (/[/\\]Core[/\\]Src[/\\]syscalls\.c$/i.test(full)) {
            const syscalls = await fs.readFile(full, 'utf8');
            const canonical = (text: string) => text.replace(/\/\*[\s\S]*?\*\/|\/\/[^\n]*/g, '').replace(/\s/g, '');
            const original = await fs.readFile(join(resources, 'templates/common/Core/Src/syscalls.c'), 'utf8');
            if (canonical(syscalls) !== canonical(original)) fail('keilRuntime', '自定义 syscalls.c 需要移植到 Arm C 运行库，未静默丢弃。');
            continue;
        }
        if (!/\.c$/i.test(full)) fail('keilUnsupported', '这个工程包含额外汇编或非 C 源文件，需要先完成对应的 Keil 适配。');
        const mapped = await mapPath(full, entry.directory);
        (mapped.startsWith('Drivers/') ? hal : app).push(mapped);
        const args = entry.arguments || commandTokens(entry.command || '');
        checkCompilerArguments(args, mapped);
        if (args.includes('-fstack-usage')) diagnosticFlags.add('-fstack-usage (GCC .su diagnostic files are not emitted by Arm Compiler)');
        const cpu = args.find(a => a.startsWith('-mcpu=')), abi = args.find(a => a.startsWith('-mfloat-abi='));
        if (cpu && cpu !== `-mcpu=${device.cpu.toLowerCase()}` || abi && abi !== `-mfloat-abi=${device.cpu === 'Cortex-M4' ? 'hard' : 'soft'}`) fail('keilCompiler', `${mapped} 的 CPU/FPU ABI 选项与所选芯片配置不一致，未忽略这些参数。`);
        const unitDefines: string[] = [], unitIncludes: string[] = [];
        for (let i = 0; i < args.length; i++) {
            const arg = args[i];
            if (arg === '-I' || arg === '-isystem') unitIncludes.push(await mapPath(args[++i], entry.directory));
            else if (arg.startsWith('-I')) unitIncludes.push(await mapPath(arg.slice(2), entry.directory));
            else if (arg.startsWith('-isystem')) unitIncludes.push(await mapPath(arg.slice(8), entry.directory));
            else if (arg === '-D') { defines.add(args[++i]); unitDefines.push(args[i]); }
            else if (arg.startsWith('-D')) { defines.add(arg.slice(2)); unitDefines.push(arg.slice(2)); }
        }
        const names = new Set<string>();
        for (const value of unitDefines) {
            const name = value.split('=')[0];
            if (names.has(name)) fail('keilCompiler', `${mapped} 重复定义 ${name}，请先消除有先后顺序依赖的宏。`);
            names.add(name);
        }
        for (const value of unitIncludes) includes.add(value);
        units.set(mapped, { defines: unitDefines, includes: [...new Set(unitIncludes)] });
    }
    if (!app.length || !hal.length || !defines.has(project.chip.id === 'STM32F407ZGTx' ? 'STM32F407xx' : 'STM32F103xB')) fail('keilConfiguration', '构建信息不完整，请检查 Nodu 工程的 CMake 配置。');
    if ([...defines, ...includes].some(s => /[;\r\n]/.test(s))) fail('keilConfiguration', '宏或路径包含 Keil 不支持的分隔符。');
    const all = [...units.values()], first = all[0];
    const commonDefines = first.defines.filter(d => all.every(u => u.defines.includes(d)));
    let prefix = first.includes.length;
    for (const unit of all) { let n = 0; while (n < prefix && unit.includes[n] === first.includes[n]) n++; prefix = n; }
    const commonIncludes = first.includes.slice(0, prefix);
    const overrides = new Map([...units].map(([path, unit]) => [path, { defines: unit.defines, includes: unit.includes }]));
    const desired = projectXml(commonDefines, commonIncludes, [...new Set(app)].sort(), [...new Set(hal)].sort(), project.preset === 'release', layout, device, overrides);
    const assets = new Map<string, Buffer>();
    await collect(join(sdkRoot, 'Drivers'), sdkRoot, assets, 'Drivers');
    for (const header of ['cmsis_compiler.h', 'cmsis_armcc.h', 'cmsis_armclang.h', device.cpu === 'Cortex-M4' ? 'core_cm4.h' : 'core_cm3.h']) {
        if (!assets.has(`Drivers/CMSIS/Include/${header}`)) fail('keilSdkMissing', `SDK 缺少 Arm Compiler 必需的 ${header}；不能用 GCC 专用头文件代替。请修复或更新完整 STM32 工具包后重试。`);
    }
    const startup = (await fs.readFile(join(resources, 'keil', device.startup), 'utf8'))
        .replace(/(Stack_Size\s+EQU\s+)0x[\da-f]+/i, (_match, prefix: string) => `${prefix}0x${layout.stack.toString(16)}`)
        .replace(/(Heap_Size\s+EQU\s+)0x[\da-f]+/i, (_match, prefix: string) => `${prefix}0x${layout.heap.toString(16)}`);
    assets.set(device.startup, Buffer.from('; Nodu: stack and heap sizes translated from the project GNU linker script.\n' + startup));
    const vectorBlock = /^__Vectors\s+[\s\S]*?^__Vectors_End/m.exec(startup)?.[0] ?? '';
    const vectorBytes = [...vectorBlock.matchAll(/^\s+DCD\s+([^;\r\n]+)/gm)].reduce((bytes, m) => bytes + 4 * m[1].split(',').length, 0);
    assets.set('retarget_arm.c', Buffer.from(runtime)); assets.set(`${device.device}.sct`, Buffer.from(scatterFor(layout, device.startup, vectorBytes)));
    assets.set('compatibility.json', Buffer.from(JSON.stringify({ schema: 1, sourceSharing: true, layout, compiler: { enums: '32-bit (GCC ABI)', ac5: 'C99, UTF-8 locale C', optimization: 'size', sourceContract: 'ISO C99; standard headers; no automatic source rewriting', diagnosticDifferences: [...diagnosticFlags] } }, null, 2) + '\n'));
    assets.set('LICENSE-startup.md', await fs.readFile(join(resources, project.chip.id === 'STM32F407ZGTx' ? 'keil/LICENSE-f4.md' : 'keil/LICENSE.md')));
    assets.set('startup-sources.json', await fs.readFile(join(resources, 'keil/sources.json')));
    const issues: CompatibilityIssue[] = [];
    const checked = new Set<string>();
    const inspect = async (file: string): Promise<void> => {
        const full = await fs.realpath(file);
        if (checked.has(full) || !within(root, full) || within(dest, full)) return;
        checked.add(full);
        const text = await fs.readFile(full, 'utf8');
        issues.push(...sourceCompatibility(relative(root, full).replace(/\\/g, '/'), text));
        for (const m of text.matchAll(/^[ \t]*#[ \t]*include\s*[<"]([^>"]+)[>"]/gm)) {
            for (const dir of [dirname(full), ...[...includes].filter(p => !p.startsWith('Drivers/')).map(p => resolve(dest, p))]) {
                const next = resolve(dir, m[1]);
                if (within(root, next) && await exists(next)) { await safeFile(next, root); await inspect(next); break; }
            }
        }
    };
    for (const path of app) await inspect(resolve(dest, path));
    if (issues.length) {
        const first = issues[0];
        throw Object.assign(new Error(`${first.file}:${first.line}:${first.column}: ${first.message} ${first.fix}（共 ${issues.length} 项，未修改业务源码）`), { code: 'keilSource', detail: { diagnostics: issues } });
    }
    const hashes = Object.fromEntries([...assets].map(([name, data]) => [name, sha(data)]));
    const fingerprint = sha(JSON.stringify([desired, hashes]));
    // Preflight every destination, including ancestors, before modifying any file.
    let repair = false;
    for (const [name, data] of assets) {
        const path = join(dest, name);
        let parent = dirname(path);
        while (within(dest, parent)) { if (await exists(parent)) await safeFile(parent, root); if (parent === dest) break; parent = dirname(parent); }
        if (await exists(path)) {
            await safeFile(path, root);
            const actual = sha(await fs.readFile(path));
            if (actual !== sha(data) && actual !== state?.assets[name]) fail('keilConflict', `${name} 已在外部修改，未覆盖。请先合并修改。`);
        } else { repair = true; }
    }
    let merged = desired, repairedDriver = false, projectChanged = false;
    if (state) {
        if (!await exists(file)) fail('keilConflict', 'Keil 工程文件已被移走，自动维护已停止。');
        await safeFile(file, root);
        const current = await fs.readFile(file, 'utf8'), repaired = repairStLinkPaths(current);
        // User scatter/startup overrides survive, but must still honor the GNU memory contract.
        for (const target of targets(parse(current))) {
            if (!names.includes(at(target, 'TargetName')?.textContent ?? '')) continue;
            const scatter = at(target, 'TargetOption/TargetArmAds/LDads/ScatterFile')?.textContent;
            if (scatter && scatter.replace(/\\/g, '/').replace(/^\.\//, '') !== `${device.device}.sct`) {
                const path = resolve(dest, scatter.replace(/\\/g, '/')); await safeFile(path, root);
                const text = (await fs.readFile(path, 'utf8')).replace(/\/\*[\s\S]*?\*\/|;[^\n]*/g, '');
                const load = /^\s*\w+\s+(0x[\da-f]+)\s+(0x[\da-f]+)\s*\{/im.exec(text);
                if (!load || Number(load[1]) !== layout.flashBase || Number(load[2]) !== layout.flashSize) fail('keilConflict', '自定义 Keil scatter 的应用 Flash 范围与 GNU 链接脚本不一致或无法确认；请先合并，未覆盖原配置。');
                if (layout.ramFunctions && !text.includes('.RamFunc') || layout.ramVectors && !text.includes('.ram_vectors')) fail('keilConflict', '自定义 Keil scatter 缺少工程所需的 RAM 函数或向量表段，未生成不等价的配置。');
                for (const group of children(at(target, 'Groups')!, 'Group')) {
                    if (at(group, 'GroupOption/CommonProperty/IncludeInBuild')?.textContent === '0') continue;
                    for (const unit of children(at(group, 'Files')!, 'File')) {
                        if (at(unit, 'FileOption/CommonProperty/IncludeInBuild')?.textContent === '0') continue;
                        const source = at(unit, 'FilePath')?.textContent ?? '';
                        if (!/\.s$/i.test(source)) continue;
                        const path = resolve(dest, source.replace(/\\/g, '/')); await safeFile(path, root);
                        const asm = await fs.readFile(path, 'utf8');
                        for (const [name, expected] of [['Stack_Size', layout.stack], ['Heap_Size', layout.heap]] as const) {
                            const value = new RegExp(`^${name}\\s+EQU\\s+(0x[\\da-f]+|[0-9]+)`, 'im').exec(asm)?.[1];
                            if (value && Number(value) !== expected) fail('keilConflict', `自定义启动文件 ${source} 的 ${name} 与 GNU 链接脚本不一致，请先合并。`);
                        }
                    }
                }
            }
        }
        repairedDriver = repaired !== current;
        merged = mergeProject(repaired, state.generated, desired);
        projectChanged = canonical(parse(current).documentElement!) !== canonical(parse(merged).documentElement!);
    }
    const options = join(dest, 'Nodu.uvoptx');
    if (await exists(options)) await safeFile(options, root);
    const previousOptions = await exists(options) ? await fs.readFile(options, 'utf8') : undefined;
    const nextOptions = previousOptions === undefined ? optionsXml(device) : repairStLinkPaths(previousOptions);
    const changed = !state || state.fingerprint !== fingerprint || repair || repairedDriver || projectChanged || previousOptions !== nextOptions;
    if (!changed) return { path: file, changed: false, created: false };
    for (const [name, data] of assets) {
        if (!await exists(join(dest, name)) || sha(await fs.readFile(join(dest, name))) !== hashes[name]) await atomic(join(dest, name), data);
    }
    if (previousOptions !== nextOptions) await atomic(options, nextOptions);
    await atomic(file, merged);
    await atomic(statePath, JSON.stringify({ schema: 1, generated: desired, assets: hashes, fingerprint } satisfies State, null, 2));
    await atomic(join(dest, 'README-Nodu.md'), '# Keil 工程\n\n打开 Nodu.uvprojx。Nodu AC6 使用 Arm Compiler 6；Nodu AC5 兼容 Arm Compiler 5。安装与芯片匹配的 STM32F1xx/F4xx DFP，并使用已授权的编译器。工程源码与 Nodu 共用，HAL/CMSIS 随此目录携带，无需下载。\n\n仅将编译器专用启动及运行库文件放在 MDK-ARM 中。ST-LINK/SWD 下载配置为初始预设，硬件烧写需使用正确接线的开发板。\n\nNodu 更新自己的文件分组、宏、包含路径和芯片配置；保留 Keil 调试设置和自建分组。若这些托管配置被手动改动，更新会停止并保留原文件。\n');
    return { path: file, changed, created: !state };
}

let installation: Promise<string | undefined> | undefined;
export function findKeil(): Promise<string | undefined> {
    if (process.platform !== 'win32') return Promise.resolve(undefined);
    return installation ??= (async () => {
        for (const key of ['HKLM\\SOFTWARE\\WOW6432Node\\Keil\\Products\\MDK', 'HKLM\\SOFTWARE\\Keil\\Products\\MDK']) {
            const output = await new Promise<string>(resolve => execFile('reg.exe', ['query', key, '/v', 'Path'], { windowsHide: true, timeout: 5000 }, (error, stdout) => resolve(error ? '' : stdout)));
            const path = output.match(/\bPath\s+REG_(?:EXPAND_)?SZ\s+(.+)/i)?.[1]?.trim();
            if (path) {
                const exe = join(path, '..', 'UV4', 'UV4.exe');
                if (await exists(exe)) return exe;
            }
        }
        return undefined;
    })();
}
export async function keilStatus(project: ProjectStatus): Promise<KeilStatus> {
    const supported = supportsKeil(project), file = join(await fs.realpath(project.path), 'MDK-ARM', PROJECT);
    return { supported, generated: await exists(file), autoSync: project.manifest.keil?.autoSync === true,
        canOpen: !!await findKeil(), projectFile: file, reason: supported ? undefined : '支持 Nodu 原生 STM32F103C8T6 / STM32F407ZGT6 工程。' };
}
export async function openKeil(project: ProjectStatus): Promise<{ path: string }> {
    if (!supportsKeil(project)) fail('keilUnsupported', '支持 Nodu 原生 STM32F103C8T6 / STM32F407ZGT6 工程。');
    if (!project.trusted) fail('untrusted', '请先信任工程再打开 Keil。');
    const executable = await findKeil();
    if (!executable) fail('keilUnavailable', '这台电脑没有可用的 Keil 5。仍可生成工程并在 Windows 上打开。');
    // The Rust sidecar canonicalizes Windows roots with a \\?\ prefix. µVision expects a normal drive path.
    const root = await fs.realpath(project.path), path = join(root, 'MDK-ARM', PROJECT); await safeFile(path, root);
    await new Promise<void>((resolve, reject) => { const child = spawn(executable!, [path], { detached: true, stdio: 'ignore', windowsHide: false }); child.once('error', reject); child.once('spawn', () => { child.unref(); resolve(); }); });
    return { path };
}
