// Build the Rust imaging library to WASM and stage it into
// scope-extension/resources/imaging/ (generated output, gitignored).
// Requires: rustup target wasm32-unknown-unknown for the pinned toolchain,
// wasm-bindgen-cli at exactly the version recorded in native/Cargo.lock.
const { execFileSync } = require('node:child_process');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');

const desktop = path.resolve(__dirname, '..');
const native = path.join(desktop, 'native');
const outDir = path.join(desktop, 'scope-extension', 'resources', 'imaging');

const pathKey =
    Object.keys(process.env).find(key => key.toLowerCase() === 'path') || 'PATH';
const env = {
    ...process.env,
    [pathKey]: [path.join(os.homedir(), '.cargo', 'bin'), process.env[pathKey] || '']
        .join(path.delimiter),
};

// The glue must come from a wasm-bindgen CLI matching the crate version the
// lockfile resolved; a mismatched CLI emits incompatible bindings.
const lock = fs.readFileSync(path.join(native, 'Cargo.lock'), 'utf8');
const lockMatch = lock.match(/name = "wasm-bindgen"\s*\nversion = "([^"]+)"/);
if (!lockMatch) {
    console.error('build-imaging: no wasm-bindgen entry in native/Cargo.lock');
    process.exit(1);
}
const expected = lockMatch[1];
let cliVersion;
try {
    cliVersion = execFileSync('wasm-bindgen', ['--version'], { env, encoding: 'utf8' })
        .trim()
        .replace(/^wasm-bindgen\s+/, '');
} catch (error) {
    console.error(
        `build-imaging: wasm-bindgen ${expected} not found; install with ` +
        `\`cargo install wasm-bindgen-cli --version ${expected} --locked\``);
    process.exit(1);
}
if (cliVersion !== expected) {
    console.error(
        `build-imaging: wasm-bindgen ${cliVersion} does not match Cargo.lock ` +
        `${expected}; install \`cargo install wasm-bindgen-cli --version ${expected} --locked\``);
    process.exit(1);
}

console.log('build-imaging: cargo build --locked --release -p nodu-imaging --features wasm --target wasm32-unknown-unknown');
try {
    execFileSync('cargo', [
        'build', '--locked', '--release', '-p', 'nodu-imaging',
        '--features', 'wasm', '--target', 'wasm32-unknown-unknown',
    ], { cwd: native, stdio: 'inherit', env });
} catch (error) {
    console.error(
        'build-imaging: cargo build failed; if the target is missing run ' +
        '`rustup target add wasm32-unknown-unknown` inside desktop/native');
    process.exit(1);
}

const wasm = path.join(
    native, 'target', 'wasm32-unknown-unknown', 'release', 'nodu_imaging.wasm');
if (!fs.existsSync(wasm)) {
    console.error(`build-imaging: expected ${wasm} after cargo build`);
    process.exit(1);
}
fs.mkdirSync(outDir, { recursive: true });
execFileSync('wasm-bindgen', [
    wasm, '--target', 'web', '--omit-default-module-path',
    '--out-dir', outDir, '--out-name', 'nodu_imaging',
], { cwd: native, stdio: 'inherit', env });

// Embedding the bytes keeps the app offline and avoids URL/CSP differences
// between the browser and Electron frontends.
const bg = path.join(outDir, 'nodu_imaging_bg.wasm');
const bytes = fs.readFileSync(bg);
fs.writeFileSync(
    path.join(outDir, 'wasm-bytes.js'),
    `// SPDX-License-Identifier: MIT\n// Generated by scripts/build-imaging.cjs; do not edit.\nexport const wasmBase64 = ${JSON.stringify(bytes.toString('base64'))};\n`);
fs.writeFileSync(
    path.join(outDir, 'wasm-bytes.d.ts'),
    `// SPDX-License-Identifier: MIT\n// Generated by scripts/build-imaging.cjs; do not edit.\nexport declare const wasmBase64: string;\n`);
console.log(`build-imaging: staged ${path.relative(desktop, outDir)} (${bytes.length} wasm bytes)`);
