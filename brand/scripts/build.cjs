'use strict';
const fs = require('node:fs');
const path = require('node:path');
const T = require('../src/tokens.cjs');
const G = require('../src/geometry.cjs');

const BRAND = path.resolve(__dirname, '..');
const REPO = path.resolve(BRAND, '..');
const THEMES = ['dark', 'light'];
const HEADER = 'Generated by brand/scripts/build.cjs from brand/src. Do not edit by hand.';

// ---------- SVG masters ----------
