def init_camera(freq=24000000, dual_buff=True, framesize=None,
                        pixformat=None, reset=True):
    import sensor
    import time
    if framesize is None:
        framesize = sensor.QVGA
    if pixformat is None:
        pixformat = sensor.RGB565
    if reset:
        # Skip the unbounded C register table loop; retain C pin/bus detection.
        sensor.reset(freq=freq, dual_buff=dual_buff, set_regs=False, choice=2)
    sensor.run(0)
    _regs = _GC2145_DEFAULT_REGS
    for _i in range(0, len(_regs), 2):
        _addr, _value = _regs[_i], _regs[_i + 1]
        if _addr == 0xff:
            time.sleep_ms(_value)
        else:
            sensor.__write_reg(_addr, _value)
    sensor.set_pixformat(pixformat)
    sensor.set_framesize(framesize)
    sensor.__write_reg(0xfe, 0x00)
    sensor.__write_reg(0xf2, 0x0f)
    time.sleep_ms(30)
    sensor.run(1)
    _result = {"registers": len(_regs) // 2, "freq": freq,
               "f2": sensor.__read_reg(0xf2),
               "format84": sensor.__read_reg(0x84)}
    print("GC2145_INIT " + repr(_result))
    return _result
