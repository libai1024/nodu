/** CMake's compile database quotes paths with spaces on both Windows and Unix. No shell is executed. */
export function commandTokens(command: string): string[] {
    const tokens: string[] = []; let value = '', quote = '';
    for (let i = 0; i < command.length; i++) {
        const c = command[i];
        if ((c === '"' || c === "'") && (!quote || quote === c)) { quote = quote ? '' : c; continue; }
        if (c === '\\' && command[i + 1] === '"') { value += command[++i]; continue; }
        if (/\s/.test(c) && !quote) { if (value) { tokens.push(value); value = ''; } } else { value += c; }
    }
    if (quote) fail('keilConfiguration', '编译参数的引号不完整，无法生成 Keil 工程。');
    if (value) tokens.push(value);
    return tokens;
}

function parse(text: string): Document {
    if (/<!DOCTYPE|<!ENTITY/i.test(text)) fail('keilConflict', 'Keil 工程包含不支持的 XML 声明，未修改文件。');
    return new DOMParser({ onError: level => { if (level !== 'warning') fail('keilConflict', 'Keil 工程 XML 无效，未修改文件。'); } }).parseFromString(text, 'application/xml');
}
const children = (node: Element, tag: string): Element[] => Array.from(node.childNodes).filter((child): child is Element => child.nodeType === 1 && (child as Element).tagName === tag);
function at(node: Element, path: string): Element | undefined {
    return path.split('/').reduce<Element | undefined>((parent, tag) => parent && children(parent, tag)[0], node);
}
const canonical = (node: Element): string => JSON.stringify([node.tagName, Array.from(node.attributes).map(a => [a.name, a.value]).sort(), Array.from(node.childNodes).filter(n => n.nodeType === 1 || !!n.textContent?.trim()).map(n => n.nodeType === 1 ? canonical(n as Element) : n.textContent?.trim())]);
const targets = (doc: Document): Element[] => Array.from(doc.getElementsByTagName('Target')).filter(t => t.parentNode?.nodeName === 'Targets');

/** Repair only Nodu's former invalid default; retain all user-selected drivers and settings. */
function repairStLinkPaths(text: string): string {
    if (!text.includes(legacyStLinkDriver)) return text;
    const doc = parse(text);
    let changed = false;
    for (const tag of ['Driver', 'Flash2', 'pMon', 'tDll']) {
        for (const node of Array.from(doc.getElementsByTagName(tag))) {
            if (node.textContent === legacyStLinkDriver) { node.textContent = stLinkDriver; changed = true; }
        }
    }
    return changed ? new XMLSerializer().serializeToString(doc) : text;
}

/** Merge only fields generated by Nodu. Debug settings, custom groups and user targets survive updates. */
export function mergeProject(current: string, baseline: string, desired: string): string {
    const doc = parse(current), old = parse(baseline), next = parse(desired);
    for (const desiredTarget of targets(next)) {
        const name = at(desiredTarget, 'TargetName')?.textContent;
        const find = (d: Document) => targets(d).find(t => at(t, 'TargetName')?.textContent === name);
        const target = find(doc), before = find(old);
        if (!target || !before) fail('keilConflict', `Keil 中的 ${name} 目标已被删除或重命名；原文件已保留。`);
        const managed = ['TargetOption/TargetCommonOption/Device', 'TargetOption/TargetCommonOption/Cpu',
            'TargetOption/TargetArmAds/Cads/Optim', 'TargetOption/TargetArmAds/Cads/VariousControls/Define', 'TargetOption/TargetArmAds/Cads/VariousControls/IncludePath'];
        for (const path of managed) {
            const a = at(target!, path), b = at(before!, path), c = at(desiredTarget, path)!;
            if (!a || !b) fail('keilConflict', `Keil 的 ${path} 配置已改变；原文件已保留。`);
            if (canonical(a!) !== canonical(b!) && canonical(a!) !== canonical(c)) fail('keilConflict', 'Keil 中由 Nodu 维护的编译配置已手动修改。请先合并这些配置；Nodu 没有覆盖原工程。');
            a!.parentNode!.replaceChild(doc.importNode(c, true), a!);
        }
        for (const path of ['TargetOption/TargetArmAds/Cads/EnumInt', 'TargetOption/TargetArmAds/Cads/VariousControls/MiscControls', 'TargetOption/TargetArmAds/LDads/ScatterFile', 'TargetOption/TargetArmAds/ArmAdsMisc/OnChipMemories']) {
            const a = at(target!, path), b = at(before!, path), c = at(desiredTarget, path);
            if (a && b && c && canonical(a) === canonical(b)) a.parentNode!.replaceChild(doc.importNode(c, true), a);
        }
        const groupParent = at(target!, 'Groups');
        if (!groupParent) fail('keilConflict', 'Keil 文件分组已改变，未覆盖原工程。');
        for (const group of children(at(desiredTarget, 'Groups')!, 'Group')) {
            const groupName = at(group, 'GroupName')?.textContent;
            const match = children(groupParent!, 'Group').find(g => at(g, 'GroupName')?.textContent === groupName);
            const base = children(at(before!, 'Groups')!, 'Group').find(g => at(g, 'GroupName')?.textContent === groupName);
            if (!match || !base) fail('keilConflict', `Keil 的 ${groupName} 分组已改变，未覆盖原工程。`);
            // Keep per-file settings written by µVision for every unchanged source path.
            const oldPaths = children(at(base!, 'Files')!, 'File').map(f => at(f, 'FilePath')?.textContent);
            const currentFiles = children(at(match!, 'Files')!, 'File');
            if (JSON.stringify(currentFiles.map(f => at(f, 'FilePath')?.textContent).sort()) !== JSON.stringify(oldPaths.sort())) fail('keilConflict', `Keil 的 ${groupName} 文件列表已手动修改，请先合并；原工程未覆盖。`);
            const imported = doc.importNode(group, true) as Element;
            for (const f of children(at(imported, 'Files')!, 'File')) {
                const retained = currentFiles.find(o => at(o, 'FilePath')?.textContent === at(f, 'FilePath')?.textContent);
                if (retained) {
                    const kept = doc.importNode(retained, true) as Element;
                    const baseFile = children(at(base!, 'Files')!, 'File').find(o => at(o, 'FilePath')?.textContent === at(f, 'FilePath')?.textContent);
                    const defaults = at(f, 'FileOption');
                    if (defaults) {
                        let option = at(kept, 'FileOption');
                        if (!option) { option = doc.importNode(defaults, true) as Element; kept.appendChild(option); }
                        if (!at(option, 'CommonProperty')) option.insertBefore(doc.importNode(at(defaults, 'CommonProperty')!, true), option.firstChild);
                        if (!at(option, 'FileArmAds')) option.appendChild(doc.importNode(at(defaults, 'FileArmAds')!, true));
                        const currentCads = at(option, 'FileArmAds/Cads'), baseCads = baseFile && at(baseFile, 'FileOption/FileArmAds/Cads');
                        if (currentCads && baseCads && canonical(currentCads) === canonical(baseCads)) currentCads.parentNode!.replaceChild(doc.importNode(at(defaults, 'FileArmAds/Cads')!, true), currentCads);
                    }
                    for (const field of ['Define', 'IncludePath']) {
                        const path = `FileOption/FileArmAds/Cads/VariousControls/${field}`;
                        const a = at(kept, path), b = baseFile && at(baseFile, path), c = at(f, path);
                        if (!b && !c) continue;
                        if ((a?.textContent ?? '') !== (b?.textContent ?? '') && (a?.textContent ?? '') !== (c?.textContent ?? '')) fail('keilConflict', `Keil 中 ${at(f, 'FileName')?.textContent} 的文件级 ${field} 已修改，未覆盖。`);
                        if (c || b) {
                            let parent = kept;
                            for (const name of path.split('/').slice(0, -1)) { let next = children(parent, name)[0]; if (!next) { next = doc.createElement(name); parent.appendChild(next); } parent = next; }
                            if (a && c) parent.replaceChild(doc.importNode(c, true), a);
                            else if (a) a.textContent = '';
                            else if (c) parent.appendChild(doc.importNode(c, true));
                        }
                    }
                    const controls = at(kept, 'FileOption/FileArmAds/Cads/VariousControls');
                    if (controls) for (const tag of ['MiscControls', 'Define', 'Undefine', 'IncludePath']) {
                        const node = children(controls, tag)[0] ?? doc.createElement(tag);
                        controls.appendChild(node);
                    }
                    f.parentNode!.replaceChild(kept, f);
                }
            }
            match!.parentNode!.replaceChild(imported, match!);
        }
    }
    return new XMLSerializer().serializeToString(doc);
}

