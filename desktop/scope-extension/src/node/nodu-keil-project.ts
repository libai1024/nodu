async function safeFile(path: string, root: string): Promise<void> {
    const actual = await fs.realpath(path);
    if (!within(root, actual)) fail('keilPath', '工程引用了目录外的文件，无法生成可移动的 Keil 工程。');
    if ((await fs.lstat(path)).isSymbolicLink()) fail('keilPath', 'Keil 工程生成不跟随符号链接。');
}
async function collect(dir: string, root: string, out: Map<string, Buffer>, prefix: string): Promise<void> {
    await safeFile(dir, root);
    for (const entry of await fs.readdir(dir, { withFileTypes: true })) {
        const full = join(dir, entry.name), rel = `${prefix}/${entry.name}`;
        if (entry.isSymbolicLink()) fail('keilPath', `工具包包含符号链接：${rel}`);
        if (entry.isDirectory()) await collect(full, root, out, rel);
        else if (entry.isFile()) out.set(rel, await fs.readFile(full));
    }
}
async function atomic(path: string, data: string | Buffer): Promise<void> {
    await fs.mkdir(dirname(path), { recursive: true });
    const temp = `${path}.${randomUUID()}.tmp`;
    try { await fs.writeFile(temp, data, { flag: 'wx' }); await fs.rename(temp, path); }
    finally { await fs.rm(temp, { force: true }); }
}

export async function generateKeil(project: ProjectStatus, compileFile: string, resources: string): Promise<KeilResult> {
    if (!supportsKeil(project)) fail('keilUnsupported', '目前支持 Nodu 原生 STM32F103C8T6 工程。');
    if (!project.trusted) fail('untrusted', '请先信任当前工程，再生成 Keil 配置。');
    const root = await fs.realpath(project.path);
    const lockDir = join(root, '.nodu');
    await fs.mkdir(lockDir, { recursive: true }); await safeFile(lockDir, root);
    const lock = join(lockDir, 'keil-update.lock');
    const handle = await fs.open(lock, 'wx').catch(() => fail('keilLocked', '另一个窗口正在维护 Keil 工程。若 Nodu 曾异常退出，请关闭所有窗口后删除 .nodu/keil-update.lock 再试。'));
    try { return await generateLocked(project, compileFile, resources); }
    finally { await handle.close(); await fs.rm(lock, { force: true }); }
}

async function generateLocked(project: ProjectStatus, compileFile: string, resources: string): Promise<KeilResult> {
    if (!supportsKeil(project)) fail('keilUnsupported', '当前支持 Nodu 原生 STM32F103C8T6 工程；外部 CMake 工程暂不支持。');
    if (!project.trusted) fail('untrusted', '请先信任当前工程，再生成 Keil 配置。');
    const root = await fs.realpath(project.path), dest = join(root, 'MDK-ARM');
    if (await exists(dest)) await safeFile(dest, root);
    const statePath = join(dest, STATE), file = join(dest, PROJECT);
    let state: State | undefined;
    if (await exists(statePath)) {
        await safeFile(statePath, root); state = JSON.parse(await fs.readFile(statePath, 'utf8'));
        if (state?.schema !== 1 || !state.assets || typeof state.generated !== 'string') fail('keilConflict', 'Keil 自动维护记录无效，未覆盖现有工程。');
    } else if (await exists(dest) && (await fs.readdir(dest)).length) fail('keilConflict', 'MDK-ARM 已有其他工程，未覆盖。请先移动或重命名该目录。');
    const toolkit = project.toolkit.root;
    if (!toolkit) fail('toolkitBroken', 'STM32 工具包不可用。');
    const sdk = await fs.realpath(join(toolkit!, 'sdk', project.chip.sdk.dir));
    const localDrivers = join(root, 'Drivers');
    const sdkRoot = await exists(join(localDrivers, 'STM32F1xx_HAL_Driver')) ? root : sdk;
    await safeFile(compileFile, root);
    const entries: CompileEntry[] = JSON.parse(await fs.readFile(compileFile, 'utf8'));
    const app: string[] = [], hal: string[] = [], defines = new Set<string>(), includes = new Set<string>();
    const mapPath = async (value: string, directory: string): Promise<string> => {
        const source = resolve(directory, value), full = await fs.realpath(source);
        if (within(join(sdkRoot, 'Drivers'), full)) {
            await safeFile(source, sdkRoot);
            return `Drivers/${relative(join(sdkRoot, 'Drivers'), full).replace(/\\/g, '/')}`;
        }
        await safeFile(source, root);
        return relative(dest, full).replace(/\\/g, '/');
    };
    let commonDefines: string | undefined;
    for (const entry of entries) {
        const full = resolve(entry.directory, entry.file);
        if (/[/\\]Startup[/\\]/i.test(full) || /[/\\]Core[/\\]Src[/\\]syscalls\.c$/i.test(full)) continue;
        if (!/\.c$/i.test(full)) fail('keilUnsupported', '这个工程包含额外汇编或非 C 源文件，需要先完成对应的 Keil 适配。');
        const mapped = await mapPath(full, entry.directory);
        (mapped.startsWith('Drivers/') ? hal : app).push(mapped);
        const args = entry.arguments || commandTokens(entry.command || '');
        const unitDefines: string[] = [];
        for (let i = 0; i < args.length; i++) {
            const arg = args[i];
            if (arg === '-I' || arg === '-isystem') includes.add(await mapPath(args[++i], entry.directory));
            else if (arg.startsWith('-I')) includes.add(await mapPath(arg.slice(2), entry.directory));
            else if (arg === '-D') { defines.add(args[++i]); unitDefines.push(args[i]); }
            else if (arg.startsWith('-D')) { defines.add(arg.slice(2)); unitDefines.push(arg.slice(2)); }
        }
        const signature = JSON.stringify(unitDefines.sort());
        if (commonDefines !== undefined && commonDefines !== signature) fail('keilUnsupported', '工程设置了不同文件各自的宏定义，暂不支持自动同步到 Keil。');
        commonDefines = signature;
    }
    if (!app.length || !hal.length || !defines.has('STM32F103xB')) fail('keilConfiguration', '构建信息不完整，请检查 Nodu 工程的 CMake 配置。');
    if ([...defines, ...includes].some(s => /[;\r\n]/.test(s))) fail('keilConfiguration', '宏或路径包含 Keil 不支持的分隔符。');
    const desired = projectXml([...defines].sort(), [...includes].sort(), [...new Set(app)].sort(), [...new Set(hal)].sort(), project.preset === 'release');
    const assets = new Map<string, Buffer>();
    await collect(join(sdkRoot, 'Drivers'), sdkRoot, assets, 'Drivers');
    const startup = (await fs.readFile(join(resources, 'keil/startup_stm32f103xb.s'), 'utf8')).replace('0x00000400', '0x00000800');
    assets.set('startup_stm32f103xb.s', Buffer.from(startup));
    assets.set('retarget_arm.c', Buffer.from(runtime)); assets.set('STM32F103C8.sct', Buffer.from(scatter));
    assets.set('LICENSE-startup.md', await fs.readFile(join(resources, 'keil/LICENSE.md')));
    assets.set('startup-sources.json', await fs.readFile(join(resources, 'keil/sources.json')));
    const hashes = Object.fromEntries([...assets].map(([name, data]) => [name, sha(data)]));
    const fingerprint = sha(JSON.stringify([desired, hashes]));
    // Preflight every destination, including ancestors, before modifying any file.
    let repair = false;
    for (const [name, data] of assets) {
        const path = join(dest, name);
        let parent = dirname(path);
        while (within(dest, parent)) { if (await exists(parent)) await safeFile(parent, root); if (parent === dest) break; parent = dirname(parent); }
        if (await exists(path)) {
            await safeFile(path, root);
            const actual = sha(await fs.readFile(path));
            if (actual !== sha(data) && actual !== state?.assets[name]) fail('keilConflict', `${name} 已在外部修改，未覆盖。请先合并修改。`);
        } else { repair = true; }
    }
    let merged = desired;
    if (state) {
        if (!await exists(file)) fail('keilConflict', 'Keil 工程文件已被移走，自动维护已停止。');
        await safeFile(file, root);
        merged = mergeProject(await fs.readFile(file, 'utf8'), state.generated, desired);
    }
    const options = join(dest, 'Nodu.uvoptx');
    if (await exists(options)) await safeFile(options, root);
    const changed = !state || state.fingerprint !== fingerprint || repair || !await exists(options);
    if (!changed) return { path: file, changed: false, created: false };
    for (const [name, data] of assets) {
        if (!await exists(join(dest, name)) || sha(await fs.readFile(join(dest, name))) !== hashes[name]) await atomic(join(dest, name), data);
    }
    if (!await exists(options)) await atomic(options, optionsXml());
    await atomic(file, merged);
    await atomic(statePath, JSON.stringify({ schema: 1, generated: desired, assets: hashes, fingerprint } satisfies State, null, 2));
    await atomic(join(dest, 'README-Nodu.md'), '# Keil 工程\n\n打开 Nodu.uvprojx。Nodu AC6 使用 Arm Compiler 6；Nodu AC5 兼容 Arm Compiler 5。安装与芯片匹配的 STM32F1xx DFP，并使用已授权的编译器。工程源码与 Nodu 共用，HAL/CMSIS 随此目录携带，无需下载。\n\n仅将编译器专用启动及运行库文件放在 MDK-ARM 中。ST-LINK/SWD 下载配置为初始预设，硬件烧写需使用正确接线的开发板。\n\nNodu 更新自己的文件分组、宏、包含路径和芯片配置；保留 Keil 调试设置和自建分组。若这些托管配置被手动改动，更新会停止并保留原文件。\n');
    return { path: file, changed, created: !state };
}

