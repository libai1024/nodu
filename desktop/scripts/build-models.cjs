// Regenerate scope-extension/resources/models/model-data.js (+ .d.ts) from
// the already-fetched, already-verified model files staged by
// fetch-models.cjs. This step is fully offline: it re-verifies each staged
// file against manifest.json before embedding it as base64 so the app ships
// the CMSIS-NN .network payloads without any runtime download.
'use strict';
const { createHash } = require('crypto');
const { readFileSync, writeFileSync, readdirSync, existsSync } = require('fs');
const { basename, join } = require('path');

const MODELS_DIR = join(__dirname, '..', 'scope-extension', 'resources', 'models');
const manifest = JSON.parse(readFileSync(join(MODELS_DIR, 'manifest.json'), 'utf-8'));

const entries = manifest.models.map(model => {
    const file = basename(model.path);
    const full = join(MODELS_DIR, model.id, file);
    if (!existsSync(full)) { throw new Error(`missing staged model file ${model.id}/${file}; run fetch:models`); }
    const data = readFileSync(full);
    if (data.length !== model.bytes) { throw new Error(`${model.id}: staged size ${data.length} != manifest ${model.bytes}`); }
    const sha = createHash('sha256').update(data).digest('hex');
    if (sha !== model.sha256) { throw new Error(`${model.id}: staged sha256 mismatch`); }
    return {
        id: model.id,
        label: model.label,
        file,
        bytes: model.bytes,
        sha256: model.sha256,
        license: model.license,
        repository: model.repository,
        revision: model.revision,
        dataBase64: data.toString('base64'),
    };
});

const js = `// SPDX-License-Identifier: MIT
// Generated by scripts/build-models.cjs from resources/models/manifest.json
// and the pinned staged .network files. Do not edit; regenerate with
// \`npm run build:models\`. The payloads are OpenMV CMSIS-NN .network files
// (MIT, see resources/licenses/network-models/) and CANNOT run on a K210.
'use strict';
/** @type {import('./model-data').NetworkModel[]} */
const NETWORK_MODELS = ${JSON.stringify(entries, null, 2)};
module.exports = { NETWORK_MODELS };
`;

const dts = `// SPDX-License-Identifier: MIT
// Generated by scripts/build-models.cjs. Do not edit.
export interface NetworkModel {
    id: string;
    label: string;
    file: string;
    bytes: number;
    sha256: string;
    license: string;
    repository: string;
    revision: string;
    dataBase64: string;
}
export declare const NETWORK_MODELS: NetworkModel[];
`;

writeFileSync(join(MODELS_DIR, 'model-data.js'), js);
writeFileSync(join(MODELS_DIR, 'model-data.d.ts'), dts);
console.log(`build-models: embedded ${entries.length} models into model-data.js`);
